# frozen_string_literal: true

require "spec_helper"
load File.expand_path("../../scripts/build_scripts", __dir__)

RSpec.describe DemoScriptCompiler do
  it "keeps every checked-in numbered demo compiled from its directory-local source" do
    expect { described_class.new(check: true).call }.to output(/Verified 7 self-contained demo scripts/).to_stdout
  end

  it "leaves no authored sidecar reads or pack operations in compiled demos" do
    scripts = Dir[File.expand_path("../../scripts/{20,22,23,24,25,26}_*.rb", __dir__)]

    expect(scripts.length).to eq(7)
    scripts.each do |path|
      source = File.read(path)
      expect(source).to include("Generated by scripts/build_scripts", "embedded_archive")
      expect(source).not_to include("File.binread", "Mobilis::EmbeddedArchive.pack", "__dir__")
    end
  end
end
