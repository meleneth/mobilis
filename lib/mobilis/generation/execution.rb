# frozen_string_literal: true

require "digest"
require "fileutils"

module Mobilis
  module Generation
    # The generation plan is owned by Manifest. Executors supply the few
    # environment-specific capabilities it requires, not an alternate plan.
    class Execution
      attr_reader :manifest

      def initialize(manifest)
        @manifest = manifest
      end

      def browser? = false

      def prepare_repository
        raise NotImplementedError
      end

      def create_builder_images
        manifest.run_plugin_hooks(:create_builder_images)
      end

      def write_service(writer, _realized_node)
        writer.write
      end

      def after_helpers
        manifest.run_plugin_hooks(:hook_after_dc_helpers)
      end

      def finish
      end
    end

    class Native < Execution
      def prepare_repository
        require "git"
        manifest.git_repo = Git.init(".")
      end

      def after_helpers
        Mobilis::Util.run_command(["./dc_test", "build"])
        super
        manifest.run_plugin_hooks(:hook_create_rails_models)
        manifest.run_plugin_hooks(:hook_after_rails_models_created)
        manifest.run_plugin_hooks(:hook_run_commands)
      end

      def commit(message)
        require "git"
        puts " -- git commit: #{message} --"
        manifest.git_repo.add(all: true)
        manifest.git_repo.commit("[mobilis] #{message}")
      end
    end

    class Browser < Execution
      def initialize(manifest, on_checkpoint:)
        super(manifest)
        raise ArgumentError, "Checkpoint callback required" unless on_checkpoint

        @on_checkpoint = on_checkpoint
        @previous_files = {}
      end

      def browser? = true

      def prepare_repository
        # The repository lives in LightningFS; the JavaScript Git adapter
        # applies these checkpoints to it after Ruby generation succeeds.
      end

      def create_builder_images
        # Preserve the Rails builder definition, but don't invoke Docker.
        manifest.plugins.each do |plugin|
          next unless plugin.is_a?(Mobilis::Plugin::RailsBuilder)

          manifest.directory_service.mkdir_rails_builder
          manifest.directory_service.chdir_rails_builder
          plugin.create_rails_builder_dockerfile
          manifest.directory_service.chdir_generate
          manifest.commit_all("Add rails builder Dockerfile")
        end
      end

      def write_service(writer, realized_node)
        return super unless writer.is_a?(Mobilis::ServiceWriter::Rails)

        writer.write_browser
        manifest.commit_all("add Rails project #{realized_node.name}")
      end

      def finish
        # Hooks can mutate files after their normal commit phase.
        # The exported ZIP must never contain uncommitted generated bytes.
        manifest.commit_all("Final generated artifacts")
      end

      def commit(message)
        root = manifest.directory_service.generate_root
        paths = Dir.glob("**/*", File::FNM_DOTMATCH, base: root)
          .reject { |path| path == "." || path == ".." || File.directory?(File.join(root, path)) }
          .sort
        writes = {}
        current = {}
        paths.each do |path|
          bytes = File.binread(File.join(root, path))
          fingerprint = Digest::SHA256.hexdigest(bytes)
          current[path] = fingerprint
          writes[path] = bytes unless @previous_files[path] == fingerprint
        end
        deletes = (@previous_files.keys - current.keys).sort
        # Native Git refuses commits with no tree changes.
        return if writes.empty? && deletes.empty?

        @on_checkpoint.call("[mobilis] #{message}", writes, deletes)
        @previous_files = current
      end
    end
  end
end
